import { mkdir, readFile, writeFile } from "node:fs/promises";
import nodePath from "node:path";
import { envVar } from "./runtime.js";

/**
 * The project lead's tools, served as an MCP server. The lead CLI (Claude, Codex) starts the stdio
 * proxy below with its run token; the proxy forwards each JSON-RPC line to the app's
 * POST /api/lead-mcp, where `handleToolMcp` (app-tools.ts, surface "lead") answers it. The lead decides when to call a tool: the
 * app only offers them (no keyword rules). Grok Build has no per-run MCP flag, so it keeps the
 * <<DELEGATE>> text protocol.
 */
export const LEAD_MCP_SERVER = "sinawi_lead";
/** Claude permission rule that allows every tool of the server. */
export const LEAD_MCP_RULE = `mcp__${LEAD_MCP_SERVER}`;
/** A collect_results wait can be long; the CLIs must not give up on the call first. */
export const LEAD_TOOL_TIMEOUT_MS = 30 * 60_000;
export const LEAD_WAIT_LIMIT_SEC = 10 * 60;

// The tools themselves (lead-only ones and every app tool) are defined in server/app-tools.ts;
// this file is how a lead's CLI run gets them.

/** The stdio MCP server the lead CLI starts: forwards every request line to the app with the run token. */
export function leadServerScript(): string {
  return `// Generated by Sinawi: the project lead's tools. Forwards MCP requests to the app.
import * as http from "node:http";
import * as readline from "node:readline";
const port = Number(process.env.SINAWI_PORT || "3001");
const token = process.env.SINAWI_COMPUTER_TOKEN || "";
const send = (message) => process.stdout.write(JSON.stringify(message) + "\\n");
// node:http, not fetch: a collect_results wait can outlast fetch's 5-minute header timeout.
const post = (body) => new Promise((resolve, reject) => {
  const req = http.request({ host: "127.0.0.1", port, path: "/api/lead-mcp", method: "POST", headers: { "content-type": "application/json", "content-length": Buffer.byteLength(body), "x-sinawi-token": token } }, (res) => {
    let text = "";
    res.setEncoding("utf8");
    res.on("data", (chunk) => { text += chunk; });
    res.on("end", () => resolve({ status: res.statusCode || 0, text }));
  });
  req.on("error", reject);
  req.end(body);
});
readline.createInterface({ input: process.stdin }).on("line", async (line) => {
  let message;
  try { message = JSON.parse(line); } catch { return; }
  if (!message || message.id === undefined || message.id === null) return;
  try {
    const res = await post(JSON.stringify(message));
    let data;
    try { data = JSON.parse(res.text); } catch { data = undefined; }
    if (data && data.jsonrpc) send(data);
    else send({ jsonrpc: "2.0", id: message.id, error: { code: -32603, message: (data && data.error) || ("Sinawi answered " + res.status) } });
  } catch (error) {
    send({ jsonrpc: "2.0", id: message.id, error: { code: -32603, message: "Sinawi is not reachable: " + (error && error.message || error) } });
  }
});
`;
}

export async function ensureLeadServerScript(dataDir: string): Promise<string> {
  const directory = nodePath.join(dataDir, "hooks");
  const file = nodePath.join(directory, "sinawi-lead.mjs");
  const script = leadServerScript();
  const current = await readFile(file, "utf8").catch(() => "");
  if (current !== script) {
    await mkdir(directory, { recursive: true });
    await writeFile(file, script, { mode: 0o600 });
  }
  return file;
}

/** How a run starts the lead server: given to buildInvocation, turned into per-CLI arguments. */
export interface LeadMcpLaunch { command: string; script: string; token: string; port: string }

export function leadMcpLaunch(script: string, token: string, nodeBinary = process.execPath): LeadMcpLaunch {
  return { command: nodeBinary, script, token, port: envVar("PORT") || "3001" };
}

/** Claude `--mcp-config` server entry. */
export function claudeLeadServer(launch: LeadMcpLaunch): Record<string, unknown> {
  return { type: "stdio", command: launch.command, args: [launch.script], env: { SINAWI_COMPUTER_TOKEN: launch.token, SINAWI_PORT: launch.port } };
}

/** Codex `-c` overrides (TOML values): the server only exists for this run, ~/.codex is untouched. */
export function codexLeadArgs(launch: LeadMcpLaunch): string[] {
  const key = `mcp_servers.${LEAD_MCP_SERVER}`;
  return [
    "-c", `${key}.command=${JSON.stringify(launch.command)}`,
    "-c", `${key}.args=[${JSON.stringify(launch.script)}]`,
    "-c", `${key}.env={SINAWI_COMPUTER_TOKEN=${JSON.stringify(launch.token)},SINAWI_PORT=${JSON.stringify(launch.port)}}`,
    "-c", `${key}.tool_timeout_sec=${Math.round(LEAD_TOOL_TIMEOUT_MS / 1000)}`,
    "-c", `${key}.startup_timeout_sec=20`,
  ];
}

