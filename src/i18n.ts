export const dictionaries: Record<Lang, Record<MessageKey, string>> = { ko, en };

// Source language until main.tsx applies the saved/system preference (tests run in ko).
let current: Lang = "ko";
const listeners = new Set<() => void>();

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang) {
  current = lang;
  if (typeof document !== "undefined") document.documentElement.lang = lang;
  for (const listener of listeners) listener();
}

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const text = dictionaries[current][key] ?? ko[key] ?? key;
  return params ? text.replace(/\{(\w+)\}/g, (match, name: string) => name in params ? String(params[name]) : match) : text;
}

/** Like `t`, but `<b>…</b>` and `<strong>…</strong>` in the message become elements. */
export function tx(key: MessageKey, params?: Record<string, string | number>): ReactNode {
  const parts = t(key, params).split(/(<(?:b|strong)>.*?<\/(?:b|strong)>)/g);
  return createElement(Fragment, null, ...parts.map((part, index) => {
    const tag = /^<(b|strong)>(.*)<\/\1>$/.exec(part);
    return tag ? createElement(tag[1], { key: index }, tag[2]) : part;
  }));
}

export function subscribeLang(listener: () => void) {
  listeners.add(listener);
  return () => { listeners.delete(listener); };
}

/** Subscribes the calling component to language changes and returns the current language. */
export function useLang(): Lang {
  return useSyncExternalStore(subscribeLang, getLang, getLang);
}

/** Subscribes the calling component to language changes and returns `t`. */
export function useT(): typeof t {
  useLang();
  return t;
}

/** A label map whose values follow the current language (property reads call `t`). */
export function translatedMap<K extends string>(keys: Record<K, MessageKey>): Record<K, string> {
  const map = {} as Record<K, string>;
  for (const name of Object.keys(keys) as K[]) Object.defineProperty(map, name, { enumerable: true, get: () => t(keys[name]) });
  return map;
}
